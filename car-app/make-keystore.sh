#!/usr/bin/env bash
# Creates the self-signed key this fork is published with, and the properties
# file Gradle reads it from. Both stay out of version control: a signing key is
# release material, not source.
#
#   ./make-keystore.sh              # random password, written to keystore.properties
#   STOREPASS=... ./make-keystore.sh
#
# Re-running is a no-op unless FORCE=1, so an existing key is never replaced by
# accident — replacing it would break updates for everyone who installed the app.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
WORKSPACE="$(cd "$HERE/.." && pwd)"
TC="$WORKSPACE/.toolchain"
JAVA_HOME="${JAVA_HOME:-$TC/jdk17}"
KEYTOOL="$JAVA_HOME/bin/keytool"
[ -x "$KEYTOOL" ] || KEYTOOL="$JAVA_HOME/bin/keytool.exe"

KS_DIR="$HERE/keystore"
KS_REL="keystore/mygocar-release.jks"
KS="$HERE/$KS_REL"
PROPS="$HERE/keystore.properties"
ALIAS="${ALIAS:-mygocar}"

if [ -e "$KS" ] && [ "${FORCE:-0}" != "1" ]; then
  echo "keystore already exists: $KS"
  echo "refusing to overwrite (set FORCE=1 to replace it deliberately)"
  exit 0
fi

if [ ! -x "$KEYTOOL" ]; then
  echo "keytool not found under $JAVA_HOME" >&2
  exit 1
fi

mkdir -p "$KS_DIR"

if [ -n "${STOREPASS:-}" ]; then
  PASS="$STOREPASS"
else
  # 24 hex chars from the OS entropy pool; no openssl dependency on Git Bash.
  PASS="$(head -c 12 /dev/urandom | od -An -tx1 | tr -d ' \n')"
fi

"$KEYTOOL" -genkeypair \
  -keystore "$KS" \
  -alias "$ALIAS" \
  -keyalg RSA -keysize 4096 -validity 10950 \
  -storepass "$PASS" -keypass "$PASS" \
  -dname "CN=MyGo Car (AGPL fork), OU=Android, O=andy8401, L=Beijing, ST=Beijing, C=CN"

cat > "$PROPS" <<EOF
# Generated by make-keystore.sh. Do not commit: this is release material.
storeFile=$KS_REL
storePassword=$PASS
keyAlias=$ALIAS
keyPassword=$PASS
EOF

echo
echo "wrote $KS"
echo "wrote $PROPS"
echo "build a signed release with: bash build.sh assembleRelease"
