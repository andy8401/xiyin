// Zero-dependency bundler: flattens src/*.js ESM modules into one index.js.
// The source style is intentionally constrained (single-line named imports,
// `export function/const` declarations, one final `export { ... }` in main.js).
import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";

const ORDER = ["utils", "session", "aes", "client", "auth", "models", "catalog", "playback", "main"];
// [^}]* also spans newlines, so multi-line named imports are supported.
const IMPORT_BLOCK_RE = /^import\s*\{[^}]*\}\s*from\s*["']\.\/([\w-]+)\.js["'];?[ \t]*$/gm;
const EXPORT_DECL_RE = /^export\s+(?=(?:async\s+)?function\b|const\b|let\b|class\b)/;
const EXPORT_LIST_RE = /^export\s*\{([^}]*)\}\s*;?\s*$/;
const TOP_DECL_RE = /^(?:async\s+)?function\s+([A-Za-z_$][\w$]*)|^(?:const|let|class)\s+([A-Za-z_$][\w$]*)/;

const pkg = JSON.parse(await readFile(new URL("../package.json", import.meta.url), "utf8"));
const manifest = JSON.parse(await readFile(new URL("../plugin.json", import.meta.url), "utf8"));
if (pkg.version !== manifest.version) throw new Error("package.json and plugin.json versions differ");
if (manifest.main !== "index.js" || manifest.playback !== "stream") throw new Error("unexpected plugin manifest");

const declarations = new Map();
const exported = [];
const chunks = [];

for (let index = 0; index < ORDER.length; index += 1) {
  const name = ORDER[index];
  let source = await readFile(new URL(`../src/${name}.js`, import.meta.url), "utf8");
  source = source.replace(IMPORT_BLOCK_RE, (_all, dependencyName) => {
    const dependency = ORDER.indexOf(dependencyName);
    if (dependency < 0 || dependency >= index) throw new Error(`src/${name}.js: dependency order violation for ${dependencyName}.js`);
    return "";
  });
  const lines = [];
  for (const original of source.split("\n")) {
    const line = original.trimEnd();
    const list = EXPORT_LIST_RE.exec(line.trim());
    if (list) {
      for (const item of list[1].split(",")) {
        const symbol = item.trim();
        if (symbol) exported.push(symbol);
      }
      continue;
    }
    const transformed = EXPORT_DECL_RE.test(line) ? line.replace(/^export\s+/, "") : line;
    const declaration = TOP_DECL_RE.exec(transformed);
    if (declaration) {
      const symbol = declaration[1] || declaration[2];
      if (declarations.has(symbol)) throw new Error(`duplicate top-level declaration ${symbol} in src/${name}.js and src/${declarations.get(symbol)}.js`);
      declarations.set(symbol, name);
    }
    lines.push(transformed);
  }
  chunks.push(`\n// ---- src/${name}.js ----\n${lines.join("\n")}`);
}

for (const symbol of exported) {
  if (!declarations.has(symbol)) throw new Error(`exported symbol ${symbol} has no declaration`);
}
if (new Set(exported).size !== exported.length) throw new Error("duplicate exported symbol");
const required = ["account", "browse", "home", "played", "recent", "search", "show", "signIn", "signOut", "stream"];
for (const symbol of required) {
  if (!exported.includes(symbol)) throw new Error(`missing MyGo callback: ${symbol}`);
}

const banner = [
  "// SPDX-License-Identifier: MIT",
  "// Generated by npm run build. Edit src/, not this file.",
  "// Single-file ES2020 ESM bundle; no runtime dependencies.",
  "// Public MyGo callbacks: " + required.join(", "),
  "",
].join("\n");
const output = banner + chunks.join("\n") + `\nexport { ${exported.join(", ")} };\n`;
await writeFile(new URL("../index.js", import.meta.url), output, "utf8");
const sha = createHash("sha256").update(output).digest("hex");
console.log(`built index.js: ${Buffer.byteLength(output)} bytes, ${declarations.size} symbols, ${exported.length} exports`);
console.log(`sha256: ${sha}`);
